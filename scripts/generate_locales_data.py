def get_strings_for_locale(loc_id, en_strings):
    # Load base if exists
    trans = DICTS.get(loc_id, {})
    if not trans:
        if loc_id == "es-419":
            trans = DICTS.get("es", {})
        elif loc_id == "pt":
            trans = DICTS.get("pt-BR", {})
        elif loc_id == "zh-Hant":
            trans = DICTS.get("zh-Hans", {})
    
    result = {}
    for k, v in en_strings.items():
        if k in trans:
            result[k] = trans[k]
        else:
            # Fallback
            result[k] = v
    return result

